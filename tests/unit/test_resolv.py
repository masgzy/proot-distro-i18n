# Tests for the DNS decision module: what /etc/resolv.conf says inside a
# container (host-following with a static fallback, the ``dns`` setting
# pinning up to three servers), the managed marker line that decides when
# a login may refresh the file, and the guest-owned file being left
# exactly as the guest left it.
#

import os

import pytest

from proot_distro import dirfd
from proot_distro.helpers import resolv
from proot_distro.helpers.rootfs import write_resolv_conf_at, open_etc
from proot_distro.constants import DEFAULT_PRIMARY_NS, DEFAULT_SECONDARY_NS


# ---------------------------------------------------------------------------
# parsing the host's resolver config
# ---------------------------------------------------------------------------

def test_parse_nameservers_dedupes_and_validates():
    text = ("search lan\n"
            "nameserver 192.168.1.1\n"
            "nameserver 192.168.1.1\n"
            "nameserver not-an-ip\n"
            "nameserver 223.5.5.5\n"
            "nameserver 2001:4860:4860::8888\n")
    assert resolv._parse_nameservers(text) == [
        "192.168.1.1", "223.5.5.5", "2001:4860:4860::8888"]


def test_parse_nameservers_caps_at_three():
    text = "\n".join(f"nameserver 10.0.0.{i}" for i in range(1, 6))
    assert resolv._parse_nameservers(text) == [
        "10.0.0.1", "10.0.0.2", "10.0.0.3"]


def test_host_nameservers_follows_the_first_usable_file(monkeypatch,
                                                          tmp_path):
    a = tmp_path / "a.conf"
    a.write_text("nameserver 1.1.1.1\n")
    b = tmp_path / "b.conf"
    b.write_text("nameserver 2.2.2.2\n")
    read = []

    def fake_read_host_file(path):
        read.append(path)
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read(64 * 1024)

    monkeypatch.setattr(resolv, "_candidate_paths",
                        lambda: iter([str(a), str(b)]))
    monkeypatch.setattr(resolv, "_read_host_file", fake_read_host_file)
    assert resolv.host_nameservers() == ["1.1.1.1"]
    # The second candidate is never read once the first answered.
    assert read == [str(a)]


def test_host_nameservers_skips_an_empty_candidate(monkeypatch, tmp_path):
    a = tmp_path / "a.conf"
    a.write_text("# nothing usable\n")
    b = tmp_path / "b.conf"
    b.write_text("nameserver 2.2.2.2\n")
    monkeypatch.setattr(resolv, "_candidate_paths",
                        lambda: iter([str(a), str(b)]))
    assert resolv.host_nameservers() == ["2.2.2.2"]


# ---------------------------------------------------------------------------
# the decision chain: dns setting > host > static default
# ---------------------------------------------------------------------------

def _setting(monkeypatch, value):
    import proot_distro.settings as settings_mod
    monkeypatch.setattr(settings_mod, "get_setting",
                        lambda name: value if name == "dns" else None)


def test_effective_nameservers_prefers_the_setting(monkeypatch):
    _setting(monkeypatch, ["223.5.5.5", "119.29.29.29"])
    monkeypatch.setattr(resolv, "host_nameservers", lambda: ["8.8.8.8"])
    assert resolv.effective_nameservers() == ["223.5.5.5", "119.29.29.29"]


def test_effective_nameservers_auto_follows_the_host(monkeypatch):
    _setting(monkeypatch, "auto")
    monkeypatch.setattr(resolv, "host_nameservers", lambda: ["192.168.1.1"])
    assert resolv.effective_nameservers() == ["192.168.1.1"]


def test_effective_nameservers_falls_back_to_static(monkeypatch):
    _setting(monkeypatch, "auto")
    monkeypatch.setattr(resolv, "host_nameservers", lambda: [])
    assert resolv.effective_nameservers() == [
        DEFAULT_PRIMARY_NS, DEFAULT_SECONDARY_NS]


def test_resolv_conf_text_carries_the_managed_marker():
    text = resolv.resolv_conf_text(["223.5.5.5"])
    assert text.startswith("# generated by proot-distro-i18n")
    assert "nameserver 223.5.5.5" in text
    assert resolv.is_managed_resolv_conf(text)


def test_legacy_static_template_is_recognized_as_managed():
    legacy = (f"nameserver {DEFAULT_PRIMARY_NS}\n"
              f"nameserver {DEFAULT_SECONDARY_NS}\n")
    assert resolv.is_managed_resolv_conf(legacy)


def test_guest_owned_resolv_conf_is_not_managed():
    assert not resolv.is_managed_resolv_conf(
        "nameserver 127.0.0.53\noptions edns0\n")
    assert not resolv.is_managed_resolv_conf(None)


# ---------------------------------------------------------------------------
# install-time write and login-time refresh, over a fake rootfs
# ---------------------------------------------------------------------------

@pytest.fixture
def fake_rootfs(tmp_path):
    rootfs = tmp_path / "rootfs"
    (rootfs / "etc").mkdir(parents=True)
    fd = os.open(str(rootfs), os.O_RDONLY | os.O_DIRECTORY)
    try:
        yield rootfs, fd
    finally:
        os.close(fd)


def test_write_resolv_conf_at_uses_effective_servers(fake_rootfs, monkeypatch):
    rootfs, fd = fake_rootfs
    monkeypatch.setattr(resolv, "effective_nameservers",
                        lambda: ["192.168.1.1", "223.5.5.5"])
    etc_fd = open_etc(fd)
    try:
        write_resolv_conf_at(etc_fd)
    finally:
        os.close(etc_fd)
    text = (rootfs / "etc" / "resolv.conf").read_text()
    assert text.startswith("# generated by proot-distro-i18n")
    assert "nameserver 192.168.1.1" in text
    assert "nameserver 223.5.5.5" in text


def test_refresh_rewrites_a_managed_file(fake_rootfs, monkeypatch):
    rootfs, fd = fake_rootfs
    monkeypatch.setattr(resolv, "effective_nameservers", lambda: ["223.5.5.5"])
    etc_fd = open_etc(fd)
    try:
        write_resolv_conf_at(etc_fd, ["8.8.8.8"])
    finally:
        os.close(etc_fd)

    resolv.refresh_guest_dns(fd)
    text = (rootfs / "etc" / "resolv.conf").read_text()
    assert "nameserver 223.5.5.5" in text
    assert "8.8.8.8" not in text


def test_refresh_leaves_a_guest_owned_file_alone(fake_rootfs, monkeypatch):
    rootfs, fd = fake_rootfs
    monkeypatch.setattr(resolv, "effective_nameservers", lambda: ["223.5.5.5"])
    # The guest's own resolver config (dhcpcd / systemd-resolved stub / a
    # hand edit): no marker line, so the login must not touch it.
    (rootfs / "etc" / "resolv.conf").write_text(
        "nameserver 127.0.0.53\noptions edns0 trust-ad\n")
    resolv.refresh_guest_dns(fd)
    assert (rootfs / "etc" / "resolv.conf").read_text() == (
        "nameserver 127.0.0.53\noptions edns0 trust-ad\n")


def test_refresh_refuses_a_symlinked_resolv_conf(fake_rootfs, monkeypatch):
    rootfs, fd = fake_rootfs
    monkeypatch.setattr(resolv, "effective_nameservers", lambda: ["223.5.5.5"])
    victim = rootfs / "host-file"
    victim.write_text("HOST DATA\n")
    (rootfs / "etc" / "resolv.conf").symlink_to(victim)
    resolv.refresh_guest_dns(fd)
    # The link and its target are untouched; nothing was written through.
    assert (rootfs / "etc" / "resolv.conf").is_symlink()
    assert victim.read_text() == "HOST DATA\n"


def test_refresh_missing_etc_is_quiet(tmp_path):
    # A rootfs with no etc at all: refresh is a no-op, never a failure.
    rootfs = tmp_path / "rootfs"
    rootfs.mkdir()
    fd = os.open(str(rootfs), os.O_RDONLY | os.O_DIRECTORY)
    try:
        resolv.refresh_guest_dns(fd)
    finally:
        os.close(fd)
