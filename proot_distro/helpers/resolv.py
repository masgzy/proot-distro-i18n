"""客人 ``/etc/resolv.conf`` 的来源决策：宿主优先，可被 ``dns`` 设置固定。

背景（为什么有这个模块）
========================

安装曾经把一份写死的 ``nameserver 8.8.8.8 / 8.8.4.4`` 放进每个新
容器，之后 login 也不再碰它。后果是在这些网络里 ``apt``、``apk``、
``dnf`` 全都解析不出域名：

* 国内网络对 8.8.8.8/8.8.4.4 的 UDP 53 常见丢包或黑洞——Alpine
  (musl resolver) 表现为 ``apk`` 长时间停在 WARNING 之后超时，
  Debian 表现为 ``Temporary failure resolving 'deb.debian.org'``；
* 开了 Android「私人 DNS」（DNS-over-TLS）的设备同样把明文 53
  拦在系统层；
* 桌面 Linux 上 pd 明明就跑在一台 DNS 完好的机器上，客人却仍然
  拿着 Google 的两个地址。

决策顺序（``effective_nameservers``）
====================================

1. ``pd setting put dns <ip[,ip...]>`` ——用户显式固定（最多 3 个，
   见下）；
2. 否则**宿主自己的解析配置**，逐级下探：

   * Termux 上 ``$PREFIX/etc/resolv.conf``，其次宿主 ``/etc/resolv.conf``
     （跟 Termux/桌面各自的实际布局对应）；
   * Android 系统属性（``getprop net.dns1`` 等，老 ROM 与部分 OEM
     上有效）；
   * IPv4 默认路由的网关（``/proc/net/route``）：Wi-Fi 下路由器
     几乎总在 53 端口上跑一个转发器；
3. 都没有才落回静态默认（阿里公共 DNS + 腾讯 DNSPod，见
   constants.py：本 fork 面向中文网络，Google 8.8.8.8 的 UDP 53
   在国内常被黑洞，正是旧版 apk/apt 解析失败的根因）。

写入带标记行（``_MANAGED_PREFIX``）；``login`` 在每次会话开始时按
当前决策**刷新**客人的 resolv.conf，但只刷自己写的文件——一旦
客人在里面自己配了东西（没有标记行），就视为客人接管，不再动它。
``install`` 与 build 的 stage 写入则无条件（那是刚解包的新树）。

为什么最多 3 个
================

musl 与 glibc 的 resolver 都只读前 3 个 nameserver（MAXNS=3），
写给第 4 个纯属安慰剂；校验与截断在这里完成，写入函数不用再想。
"""

from __future__ import annotations

import ipaddress
import os
import subprocess

from proot_distro import dirfd
from proot_distro.constants import (
    DEFAULT_PRIMARY_NS,
    DEFAULT_SECONDARY_NS,
    IS_TERMUX,
    TERMUX_PREFIX,
)

__all__ = (
    "effective_nameservers",
    "host_nameservers",
    "is_managed_resolv_conf",
    "refresh_guest_dns",
    "resolv_conf_text",
)

# 识别"这是我们写的 resolv.conf"的第一行标记。写成完整的独立注释行，
# 客人自己接管文件时（dhcpcd、systemd-resolved stub、手工编辑）不会
# 保留这行，登录侧就能识别"不是我的了，别动"。
_MANAGED_PREFIX = "# generated by proot-distro-i18n (managed; edit via 'setting dns')"

# musl / glibc 各自最多读 3 个 nameserver（MAXNS=3）。
_MAX_NS = 3

# 一份 resolv.conf 的读入上限： strangers 可写的文件不决定读多少字节。
_READ_LIMIT = 64 * 1024

# 旧版（无标记行）安装写进客人的静态模板，刷新时同样识别为"我们的"。
# 两代都认：新静态默认（223.5.5.5/119.29.29.29）与上游继承的旧值
# （8.8.8.8/8.8.4.4）——升级后 login 才能把旧版装出的容器也刷新掉。
_LEGACY_TEMPLATE = (
    f"nameserver {DEFAULT_PRIMARY_NS}\n"
    f"nameserver {DEFAULT_SECONDARY_NS}\n"
)
_LEGACY_UPSTREAM_TEMPLATE = (
    "nameserver 8.8.8.8\n"
    "nameserver 8.8.4.4\n"
)

# Android 系统属性里可能带 nameserver 的那几个（老 ROM / 部分 OEM）。
# 逐个读 ``getprop``，值要么是 IP 要么为空，无效值静默丢弃。
_ANDROID_DNS_PROPS = (
    "net.dns1", "net.dns2",
    "dhcp.wlan0.dns1", "dhcp.wlan0.dns2",
    "net.rmnet0.dns1", "net.rmnet0.dns2",
)

# getprop 的候选路径：宿主 Termux 的 PATH 不一定带 /system/bin。
_GETPROPS = ("/system/bin/getprop", "/system/xbin/getprop")


def host_nameservers() -> list:
    """宿主当前在用的 nameserver 列表（已校验，最多 3 个）。

    Termux 上按序下探，第一个读出合法 nameserver 的来源胜出：

    1. ``$PREFIX/etc/resolv.conf``（termux 环境自带的解析配置）；
    2. Android 系统属性 ``net.dns1`` 等（``getprop``，老 ROM 与部分
       OEM 上有效；新 Android 常为空）；
    3. IPv4 默认路由的网关（Wi-Fi 路由器几乎总跑 53 端口的转发器）；

    桌面 Linux 上读宿主的 ``/etc/resolv.conf``。读入封顶 64 KiB
    ——``/etc/resolv.conf`` 正常不过百来字节，再多就是异常输入。
    每一级都拿不到才交给静态默认（见 effective_nameservers）。
    """
    for path in _candidate_paths():
        text = _read_host_file(path)
        if text is None:
            continue
        servers = _parse_nameservers(text)
        if servers:
            return servers[:_MAX_NS]
    if IS_TERMUX:
        for probe in (_android_prop_nameservers, _default_route_gateway):
            servers = probe()
            if servers:
                return servers[:_MAX_NS]
    return []


def _candidate_paths():
    if IS_TERMUX:
        yield os.path.join(TERMUX_PREFIX, "etc", "resolv.conf")
    yield "/etc/resolv.conf"


def _read_host_file(path: str):
    """宿主侧配置文件的文本（宿主自己的文件，跟随符号链接是本意）。"""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read(_READ_LIMIT)
    except OSError:
        return None


def _parse_nameservers(text: str) -> list:
    """文本里的合法 nameserver 地址（去重、保序、最多 3 个）。"""
    seen, out = set(), []
    for line in text.splitlines():
        tokens = line.split()
        if len(tokens) < 2 or tokens[0] != "nameserver":
            continue
        try:
            ip = ipaddress.ip_address(tokens[1])
        except ValueError:
            continue
        token = str(ip)
        if token not in seen:
            seen.add(token)
            out.append(token)
    return out[:_MAX_NS]


def _android_prop_nameservers() -> list:
    """Android 系统属性里的 nameserver（老 ROM / 部分 OEM 上有效）。

    新 Android 的 ``net.dns*`` 通常为空（解析走 netd，可能还是
    DNS-over-TLS），所以这只是第二梯队的探针：读出来就用，读不出来
    不吭声。``getprop`` 从绝对路径里挑（PATH 不一定带 /system/bin），
    每次调用限时 2 秒——一个版本探测不该让安装卡住。
    """
    import shutil

    binary = next(
        (path for path in _GETPROPS if os.access(path, os.X_OK)),
        shutil.which("getprop"),
    )
    if not binary:
        return []
    servers = []
    for prop in _ANDROID_DNS_PROPS:
        try:
            result = subprocess.run(
                [binary, prop], capture_output=True, text=True,
                timeout=2, check=False,
            )
            value = (result.stdout or "").strip()
        except (OSError, ValueError, subprocess.SubprocessError):
            continue
        if not value or value == "0.0.0.0":
            continue
        try:
            token = str(ipaddress.ip_address(value))
        except ValueError:
            continue
        if token not in servers:
            servers.append(token)
    return servers[:_MAX_NS]


def _default_route_gateway() -> list:
    """IPv4 默认路由的网关（一个 nameserver 候选，Wi-Fi 场景几乎总对）。

    ``/proc/net/route`` 的 Gateway 字段是网络字节序的小端十六进制
    （``C0A80101`` = 192.168.1.1）；Destination 全零的那行是默认路由。
    路由器几乎总在 53 端口跑一个转发器，蜂窝网络的网关也常是运营商
    DNS。只取一条（多网卡时取第一条默认路由即可）；0.0.0.0 与解析
    不出的值全部丢弃。IPv6-only 的网络探不到——那种环境本来也该由
    用户 ``pd setting put dns`` 显式固定。
    """
    try:
        with open("/proc/net/route", "r", encoding="utf-8",
                  errors="replace") as fh:
            lines = fh.read(_READ_LIMIT).splitlines()
    except OSError:
        return []
    for line in lines[1:]:
        fields = line.split()
        if len(fields) < 3 or fields[1].lower() != "00000000":
            continue
        try:
            raw = bytes.fromhex(fields[2].zfill(8))
        except ValueError:
            continue
        token = ".".join(str(b) for b in raw[::-1])
        if token == "0.0.0.0":
            continue
        try:
            ipaddress.ip_address(token)
        except ValueError:
            continue
        return [token]
    return []


def effective_nameservers() -> list:
    """最终写给客人的 nameserver 列表（``dns`` 设置 > 宿主 > 静态默认）。"""
    from proot_distro.settings import get_setting

    try:
        chosen = get_setting("dns")
    except KeyError:
        chosen = "auto"
    if isinstance(chosen, list) and chosen:
        return list(chosen[:_MAX_NS])
    servers = host_nameservers()
    if servers:
        return servers
    return [DEFAULT_PRIMARY_NS, DEFAULT_SECONDARY_NS]


def resolv_conf_text(servers=None) -> str:
    """一份带管理标记的 resolv.conf 文本。"""
    if servers is None:
        servers = effective_nameservers()
    lines = [_MANAGED_PREFIX]
    lines += [f"nameserver {srv}" for srv in servers[:_MAX_NS]]
    return "\n".join(lines) + "\n"


def is_managed_resolv_conf(text) -> bool:
    """这份内容是否是本程序管理的 resolv.conf（标记行或旧静态模板）."""
    if not isinstance(text, str):
        return False
    if text.startswith(_MANAGED_PREFIX):
        return True
    # 兼容旧版安装写入的无标记静态模板（两代静态默认都认）。
    return text in (_LEGACY_TEMPLATE, _LEGACY_UPSTREAM_TEMPLATE)


def refresh_guest_dns(rootfs_fd: int) -> None:
    """会话开始前把客人的 resolv.conf 刷新为当前决策（host 侧写）。

    刷新条件（见 :func:`is_managed_resolv_conf`）：文件是我们写的
    （标记行或旧静态模板），或缺失（给一个没配置 DNS 的容器补上）。
    客人 root 自己接管过的（自己写的名字服务器/搜索域，或干脆
    把名字换成了符号链接/FIFO）一律不动——每次 login 冲掉客人
    自己的解析配置，和把它删掉一样是破坏。写入走 rootfs.py 的
    既有安全通道（O_NOFOLLOW 打开 etc、unlink+O_EXCL 重建条目），
    全程持有 rootfs 描述符。失败只静默跳过（尽力而为）。
    """
    from proot_distro.helpers.rootfs import open_etc, write_resolv_conf_at

    if rootfs_fd is None:
        return
    etc_fd = open_etc(rootfs_fd)
    if etc_fd is None:
        return
    try:
        present, current = _read_guest_resolv(etc_fd)
        if present and not is_managed_resolv_conf(current):
            return
        write_resolv_conf_at(etc_fd)
    except OSError:
        pass
    finally:
        os.close(etc_fd)


def _read_guest_resolv(etc_fd: int):
    """客人 etc 下 resolv.conf 的 (条目存在, 文本)。

    文本为 None 表示“存在但不是可读的常规文件”（符号链接/FIFO 被
    open_regular_at 拒绝）——调用方把它当客人接管处理，不做写入。
    条目不存在时返回 (False, None)，调用方可补写一份。
    """
    try:
        fd, _st = dirfd.open_regular_at(etc_fd, "resolv.conf", os.O_RDONLY)
    except FileNotFoundError:
        return False, None
    except OSError:
        return True, None
    try:
        try:
            data = os.read(fd, _READ_LIMIT)
        except OSError:
            return True, None
        # 再读一次确认已到结尾（超过上限的文件视作异常输入）。
        if os.read(fd, 1):
            return True, None
        return True, data.decode("utf-8", "replace")
    finally:
        os.close(fd)
